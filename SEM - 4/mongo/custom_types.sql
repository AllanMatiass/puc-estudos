
CREATE OR REPLACE TYPE CPF AS OBJECT (
    VALOR VARCHAR2(14)
);
/

SET SERVEROUTPUT ON;

DECLARE 
    v_cpf CPF;
begin
    v_cpf := CPF('123.456.789-00');
    DBMS_OUTPUT.PUT_LINE('cpf: ' || v_cpf.VALOR);
    DBMS_OUTPUT.PUT_LINE('tamanho: ' || LENGTH(v_cpf.VALOR));
END;
/


